  using(bucket_id='workout-media' and (storage.foldername(name))[1]=auth.uid()::text);

-- Signed URLs are generated by an authenticated client. Friends can only discover
-- a photo path through this RPC when the post itself is visible to them.
create or replace function public.get_friend_feed_v3()
returns table(
  id uuid,
  user_id uuid,
  session_id uuid,
  username text,
  avatar_url text,
  summary text,
  caption text,
  photo_path text,
  created_at timestamptz,
  started_at timestamptz,
  ended_at timestamptz,
  exercise_count bigint,
  total_sets bigint,
  total_volume numeric,
  total_distance numeric,
  exercise_names text
)
language sql stable security definer set search_path = public as $$
  select
    wp.id, wp.user_id, wp.session_id, pp.username::text, pp.avatar_url,
    wp.summary, wp.caption, wp.photo_path, wp.created_at,
    ws.started_at, ws.ended_at,
    count(distinct wset.exercise_name),
    count(wset.id),
    coalesce(sum(coalesce(wset.weight_kg,0) * coalesce(wset.reps,0)),0),
    coalesce(sum(coalesce(wset.distance_km,0)),0),
    coalesce(string_agg(distinct wset.exercise_name, ', '),wp.summary)
  from public.workout_posts wp
  join public.public_profiles pp on pp.user_id=wp.user_id
  join public.workout_sessions ws on ws.id=wp.session_id
  left join public.workout_sets wset on wset.session_id=wp.session_id
  where wp.user_id=auth.uid() or public.are_friends(auth.uid(),wp.user_id)
  group by wp.id,wp.user_id,wp.session_id,pp.username,pp.avatar_url,wp.summary,wp.caption,wp.photo_path,wp.created_at,ws.started_at,ws.ended_at
  order by wp.created_at desc
  limit 60;
$$;
grant execute on function public.get_friend_feed_v3() to authenticated;

-- Allow friends who can see a workout post to download its private image.
-- We use a SECURITY DEFINER function to mint the path visibility; Storage itself
-- remains private and signed URLs are created client-side for the authenticated user.
-- Add a read policy for photo objects referenced by a visible post.
drop policy if exists "workout media visible post read" on storage.objects;
create policy "workout media visible post read" on storage.objects for select to authenticated
using (
  bucket_id='workout-media'
  and exists (
    select 1 from public.workout_posts p
    where p.photo_path = storage.objects.name
      and (p.user_id = auth.uid() or public.are_friends(auth.uid(), p.user_id))
  )
);

