-- FitHub 1.3.0 update
-- Gym-session invites, optional workout-post photos and richer feed data.
-- Run once in Supabase Dashboard -> SQL Editor.

alter table public.workout_posts add column if not exists caption text;
alter table public.workout_posts add column if not exists photo_path text;

create table if not exists public.gym_invites (
  id uuid primary key default gen_random_uuid(),
  sender_id uuid not null references public.public_profiles(user_id) on delete cascade,
  recipient_id uuid not null references public.public_profiles(user_id) on delete cascade,
  session_at timestamptz not null,
  gym_name text,
  workout_name text,
  note text,
  status text not null default 'pending' check (status in ('pending','accepted','declined','cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (sender_id <> recipient_id)
);

create index if not exists gym_invites_sender_time_idx on public.gym_invites(sender_id, session_at desc);
create index if not exists gym_invites_recipient_time_idx on public.gym_invites(recipient_id, session_at desc);

alter table public.gym_invites enable row level security;
drop policy if exists "gym invites involved read" on public.gym_invites;
drop policy if exists "gym invites sender insert" on public.gym_invites;
drop policy if exists "gym invites involved update" on public.gym_invites;
drop policy if exists "gym invites sender delete" on public.gym_invites;
create policy "gym invites involved read" on public.gym_invites
  for select to authenticated
  using (sender_id = auth.uid() or recipient_id = auth.uid());
create policy "gym invites sender insert" on public.gym_invites
  for insert to authenticated
  with check (
    sender_id = auth.uid()
    and recipient_id <> auth.uid()
    and public.are_friends(auth.uid(), recipient_id)
  );
create policy "gym invites involved update" on public.gym_invites
  for update to authenticated
  using (sender_id = auth.uid() or recipient_id = auth.uid())
  with check (sender_id = auth.uid() or recipient_id = auth.uid());
create policy "gym invites sender delete" on public.gym_invites
  for delete to authenticated
  using (sender_id = auth.uid());

